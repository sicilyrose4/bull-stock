"""Bundle the Figma-exported SVG icons into icons.js so they render inline.

Inline SVGs can be recolored with CSS (`color`), which lets one icon work in
both pink Mock Mode and blue Real Mode, and works even when index.html is
opened straight from disk (CSS masks and fetch() don't on file://).
Shapes are untouched; only the accent/gray paint is swapped for currentColor.
Run from the project root:  python3 tools/build-icons.py
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
ICONS = {
    'home': 'nav-home', 'portfolio': 'nav-portfolio', 'community': 'nav-community',
    'history': 'nav-history', 'search': 'nav-search',
    'close': 'icon-close-pink', 'back': 'icon-back-pink',
    'plus': 'icon-plus-white', 'question': 'icon-question', 'questionLg': 'icon-question-dark',
    'chevron': 'chevron', 'heart': 'icon-heart', 'message': 'icon-message',
    'verified': 'verified', 'coinC': 'coin-c', 'coinBar': 'coin-bar',
    'squiggle': 'mock-squiggle-pink', 'radioOn': 'radio-pink-on', 'radioOff': 'radio-off',
    'play': 'icon-play', 'bell': 'icon-bell', 'gear': 'icon-gear',
    'tutCoins': 'tut-coins', 'tutPortfolio': 'tut-portfolio', 'tutTrends': 'tut-trends',
}
RECOLOR = re.compile(r'#(FD5CC5|737C82|5C87FD)\b|"black"', re.I)

# Single-color white icons that should follow the surrounding text color.
WHITE_TO_CURRENT = {'coinC', 'coinBar', 'bell', 'gear', 'heart', 'message', 'play'}

out = {}
for key, name in ICONS.items():
    svg = (ROOT / 'assets' / f'{name}.svg').read_text()
    svg = re.sub(r'\s(style|preserveAspectRatio|overflow)="[^"]*"', '', svg)
    svg = RECOLOR.sub(lambda m: '"currentColor"' if m.group(0) == '"black"' else 'currentColor', svg)
    if key in WHITE_TO_CURRENT:
        svg = re.sub(r'"(white|#FFFFFF|#F4F3F1)"', '"currentColor"', svg, flags=re.I)
    out[key] = ' '.join(svg.split())

(ROOT / 'icons.js').write_text(
    '// Generated by tools/build-icons.py from assets/*.svg — do not edit by hand.\n'
    'const ICONS = ' + json.dumps(out, indent=1) + ';\n')
print(f'wrote {len(out)} icons')
